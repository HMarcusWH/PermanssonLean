"""Render the supplied X1 matrix literals without changing their reference JSON.

The generated Lean file proves its entries equal the rational formula and the
original typed kernel atoms. This renderer is not a theorem prover.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
CERTIFICATE = ROOT / "research/paper_closures/spec/certificates/x1_exact_tables.json"
TARGET = ROOT / "PermanssonResearch/X1/ExactMatrixTables.lean"


def render() -> str:
    data = json.loads(CERTIFICATE.read_text(encoding="utf-8"))
    assert data["state_order"] == [[q1, q2, x]
        for q1 in range(3) for q2 in range(3) for x in range(2)]
    assert set(data["models"]) == {f"{mode}/{protocol}"
        for mode in ("E", "L") for protocol in ("baseline", "action", "update", "joint")}
    lines = [
        "import PermanssonResearch.X1.ExactTerminalTables",
        "",
        "/-! All 8 × 18 × 18 supplied rational matrix literals.",
        "Generated by verification/research/generate_x1_matrix_tables.py.",
        "The JSON is input data; matrix_eq_entry checks every candidate in Lean.",
        "Certificate SHA256: " + hashlib.sha256(CERTIFICATE.read_bytes()).hexdigest(),
        "-/",
        "",
        "namespace PermanssonResearch.X1.InterventionNumerics",
        "set_option autoImplicit false",
        "",
        "def matrixData (learner restrain reset : Bool) : Fin 18 → Fin 18 → ℚ :=",
        "  match learner, restrain, reset with",
    ]
    for learner, mode in ((False, "E"), (True, "L")):
        for restrain, reset, protocol in ((False, False, "baseline"),
            (True, False, "action"), (False, True, "update"), (True, True, "joint")):
            matrix = data["models"][f"{mode}/{protocol}"]["matrix"]
            assert len(matrix) == 18 and all(len(row) == 18 for row in matrix)
            assert all(re.fullmatch(r"[0-9]+(?:/[1-9][0-9]*)?", value)
                       for row in matrix for value in row)
            flags = ", ".join(str(flag).lower() for flag in (learner, restrain, reset))
            lines.append(f"  | {flags} => ![")
            lines.extend("    ![" + ", ".join(row) + "]" + ("," if i < 17 else "]")
                         for i, row in enumerate(matrix))
    lines.extend("""

def matrix (learner restrain reset : Bool) (y z : Y) : ℚ :=
  matrixData learner restrain reset (stateIndex y) (stateIndex z)

/-- A concrete normalized corner also makes literal corruption diagnostics explicit. -/
theorem baseline_corner_literal :
    matrix false false false ((0,0),false) ((0,0),false) = (3/4 : ℚ) := by
  norm_num [matrix, matrixData, stateIndex]

set_option maxRecDepth 16384 in
set_option maxHeartbeats 0 in
theorem matrix_eq_entry : ∀ (learner restrain reset : Bool) (y z : Y),
    matrix learner restrain reset y z = entry learner restrain reset y z := by
  decide +kernel

set_option maxRecDepth 16384 in
theorem stateIndex_surjective : Function.Surjective stateIndex := by
  decide +kernel

theorem matrix_nonneg (learner restrain reset : Bool) (y z : Y) :
    0 ≤ matrix learner restrain reset y z := by
  rw [matrix_eq_entry]
  exact entry_nonneg learner restrain reset y z

theorem matrix_sum_one (learner restrain reset : Bool) (y : Y) :
    (∑ z : Y, matrix learner restrain reset y z) = 1 := by
  simp_rw [matrix_eq_entry]
  exact entry_sum_one learner restrain reset y

/-- The literal arrays, in the supplied lexicographic state order, equal the
actual original typed baseline/action/update/joint kernel atoms for both modes. -/
theorem matrix_atom_eq (m : Mode) (r u : Bool) (y z : Y) :
    (protocolModel m r u).inducedKernel y {z} =
      ENNReal.ofReal (matrix (learnerFlag m) r u y z : ℝ) := by
  rw [matrix_eq_entry]
  exact protocol_atom_eq m r u y z

end PermanssonResearch.X1.InterventionNumerics
""".strip("\n").splitlines())
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        ok = TARGET.is_file() and TARGET.read_bytes() == expected.encode("utf-8")
        print("PASS: exact supplied matrix literal rendering" if ok else "FAIL: matrix rendering differs")
        return 0 if ok else 1
    TARGET.write_bytes(expected.encode("utf-8"))
    print(TARGET)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
